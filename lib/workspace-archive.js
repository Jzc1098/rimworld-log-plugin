/**
 * Daily snapshots of the work area, and a migration pack that carries only the newest one.
 *
 * Why this exists: the work area holds both hand-written findings and generated artifacts, and only the
 * first kind cannot be produced again. The first design therefore tried to snapshot "the part that would
 * be a real loss" - and got it wrong, because deciding that by hand meant a whitelist, and the whitelist
 * named neither the 33 `fix-*` project directories nor the plugin itself. It reported success on a
 * snapshot that held almost none of the work.
 *
 * The rule now is the other way round: take everything, and name only what is known to be regenerated by
 * a build or a VCS. A list of exclusions can be argued about and is printed in every report; a list of
 * inclusions fails silently the moment something new appears.
 *
 * Two rules this module enforces and one it deliberately does not:
 *
 *  - Retention is by day, not by run. Snapshotting twice on the same day overwrites that day's snapshot
 *    instead of adding a fourth. The example that defines the expected behaviour: archiving on the 1st,
 *    6th, 10th and 15th leaves exactly the 6th, 10th and 15th - the three newest days.
 *  - A migration pack carries the newest snapshot only. Older snapshots stay in the snapshots directory,
 *    because a pack is something you hand to another machine, and stale copies in it are how two machines
 *    end up disagreeing about which findings are current. `snapshot` and `export` are separate actions
 *    for exactly this reason.
 *  - Nothing here decides which snapshot is "correct". It records what was on disk, with sizes, and says
 *    what it left out. A snapshot is evidence about content, not a judgement about it.
 *
 * Every path this module deletes is checked to be inside the snapshots directory before removal. That
 * check is the only thing standing between a configuration mistake (a stray `RIMLOG_WORKSPACE_DIR` or
 * `RIMLOG_SNAPSHOT_DIR`) and a recursive delete of the user's work, so it is not optional.
 *
 * @module rimworld-log/workspace-archive
 */

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';

import { get } from './config.js';

const MANIFEST = 'manifest.json';
const MANIFEST_SCHEMA = 'rimworld-log.snapshot';
const MANIFEST_SCHEMA_VERSION = 1;
const PACK_SCHEMA = 'rimworld-log.migration-pack';

/** Days of snapshots to keep. The stated requirement is three; it is a parameter, not a constant. */
export const DEFAULT_KEEP_DAYS = 3;

/**
 * Directory names never walked, at any depth.
 *
 * A whitelist was tried first and failed in a way worth recording: the real work area holds 33 `fix-*`
 * project directories, the plugin itself and `_tools`, none of which a whitelist named - so a
 * "successful" 63-file snapshot had silently captured almost none of the work. A whitelist fails
 * silently every time a new directory appears; this list fails loudly and only for names someone
 * thought about.
 *
 * These particular names are build and VCS internals. What they skip is measured, not assumed: on the
 * real work area only two `bin` directories exist, holding 4.8 MB of test DLLs. Every name here is
 * reported back as `excludedDirs` so the decision is visible rather than implicit.
 *
 * A per-file size cap was also tried and deliberately removed - see `walk`.
 */
const DEFAULT_EXCLUDE = new Set([
  'node_modules', '.git', '.svn', '.hg',
  'bin', 'obj', '.vs', '.idea', '__pycache__',
]);

/**
 * Files that must never travel in a migration pack.
 *
 * The plugin's cursor and per-source summary files are named after the absolute path of a log file,
 * base64url-encoded. Copied to another machine they are worse than useless: they name a log that does
 * not exist there, so the first scan would either find nothing or believe it had already read
 * something. `install-state.json` is the opposite case and is kept - it is what makes the "what changed
 * since the last install" report meaningful after a move.
 */
const NEVER_COPY = [
  /\.bak-\d{8}-\d{6}$/,
  /\.last\.json$/,
  /^[A-Za-z0-9_-]{40,}\.json$/,
];

/**
 * Candidate work areas, in probe order, for when `RIMLOG_WORKSPACE_DIR` is not set.
 *
 * A hard-coded default was the first attempt and it is wrong: snapshotting a directory that does not
 * exist produces an empty snapshot that reports success. Probing for the first candidate that actually
 * holds findings documents is the honest version of "find the work area" - and if none matches, the
 * caller is told that instead of being handed an empty archive.
 */
const CANDIDATE_ROOTS = [
  () => process.env.DSH_WORKSPACE_DIR,
  () => process.env.DSH_SESSION_WORKSPACE,
  () => process.env.RIMLOG_WORKSPACE_DIR,
  () => path.join(os.homedir(), '.dsh', 'rimworld-log', 'workspace'),
];

/** True when a directory exists and holds at least one markdown file at its root. */
function looksLikeWorkArea(dir) {
  if (!dir) return false;
  try {
    if (!fs.statSync(dir).isDirectory()) return false;
    return fs.readdirSync(dir, { withFileTypes: true })
      .some((e) => e.isFile() && e.name.toLowerCase().endsWith('.md'));
  } catch {
    return false;
  }
}

/**
 * The work area this module snapshots.
 *
 * Resolution order: the explicit override, then the first candidate that looks like a work area, then
 * the historical default. `RIMLOG_WORKSPACE_DIR` is authoritative even when the directory does not
 * exist - a user who names a path should be told it is wrong, not silently redirected elsewhere.
 */
export function workspaceRoot() {
  // 显式指定优先：环境变量 RIMLOG_WORKSPACE_DIR 或 settings.json 的 workspaceDir（设置层）。
  // 这条路径是 v1.6.9 补的——此前的候选列表里写死过一个开发机目录，公开版删掉它之后，
  // 名字用户必须能通过「设置 → RimWorld 日志 → 工作区目录」指过来，否则会退回空默认目录。
  const configured = get('workspaceDir').value;
  if (typeof configured === 'string' && configured !== '') return configured;
  for (const candidate of CANDIDATE_ROOTS) {
    const dir = candidate();
    if (looksLikeWorkArea(dir)) return dir;
  }
  return path.join(os.homedir(), '.dsh', 'rimworld-log', 'workspace');
}
/** True when the resolved work area exists; callers report a false here rather than archiving nothing. */
export function workspaceExists() {
  try {
    return fs.statSync(workspaceRoot()).isDirectory();
  } catch {
    return false;
  }
}

/** Where snapshots live. Deliberately beside the plugin's other runtime data rather than inside the work area. */
export function snapshotsDir() {
  return process.env.RIMLOG_SNAPSHOT_DIR
    ?? path.join(path.dirname(workspaceRoot()), 'snapshots');
}

/** Today as `YYYY-MM-DD`, in local time. Local, because "a day" here means the user's day. */
export function today(now = new Date()) {
  const pad = (n) => String(n).padStart(2, '0');
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

function stamp(now = new Date()) {
  const pad = (n) => String(n).padStart(2, '0');
  return `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}`
    + `-${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
}

/** True when `child` is inside `parent`, after resolving both. Guards every delete. */
function isInside(parent, child) {
  const rel = path.relative(path.resolve(parent), path.resolve(child));
  return rel !== '' && !rel.startsWith('..') && !path.isAbsolute(rel);
}

function shouldSkip(name) {
  return NEVER_COPY.some((re) => re.test(name));
}

/**
 * Recursively list files under a directory as `{ rel, abs, size }`, both relative-to-`base` and absolute.
 *
 * Returning the absolute path alongside the relative one matters: an earlier version returned only the
 * relative path and the caller rebuilt the absolute path with `path.join(root, rel)`, which silently
 * dropped the directory the walk started in (`_archive/loose/note.md` became `<root>/loose/note.md`).
 * The file then failed its existence check and the whole subtree was skipped without an error.
 *
 * Size is not a criterion. A per-file cap was tried and removed: the files it excluded on the real work
 * area were the decompiled sources - the ones that are hardest to produce again, because the mod DLL they
 * came from may be gone and the parameters used are not recorded anywhere. A cap trades a real loss for
 * disk space, and disk space is the cheaper of the two.
 */
function walk(dir, base = dir, out = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (DEFAULT_EXCLUDE.has(entry.name.toLowerCase())) continue;
    if (shouldSkip(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, base, out);
      continue;
    }
    if (!entry.isFile()) continue;
    let size = 0;
    try {
      size = fs.statSync(full).size;
    } catch {
      continue;
    }
    out.push({ rel: path.relative(base, full).split(path.sep).join('/'), abs: full, size });
  }
  return out;
}

/** Copy one file, creating parent directories, and report its size. */
function copyInto(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
  return fs.statSync(to).size;
}

/**
 * The files a snapshot is made of: everything in the work area except what is known to be regenerable.
 *
 * Every top-level entry is walked, and every regular file is taken. Size is not a criterion, and neither
 * is extension: an earlier version took only root-level `.md` outside the named trees, which is the same
 * class of silent omission as the whitelist bug. Markdown is tagged `doc` and everything else `tree`,
 * which only affects how the manifest describes it.
 *
 * `excludedDirs` names the build/VCS directories left out, so that decision is visible.
 */
export function snapshotSources(root = workspaceRoot()) {
  const sources = [];
  const excludedDirs = [];
  let entries;
  try {
    entries = fs.readdirSync(root, { withFileTypes: true });
  } catch {
    return { sources, excludedDirs };
  }

  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.') || entry.name === MANIFEST) continue;
    if (DEFAULT_EXCLUDE.has(entry.name.toLowerCase())) {
      excludedDirs.push(entry.name);
      continue;
    }
    const full = path.join(root, entry.name);

    if (entry.isFile()) {
      if (shouldSkip(entry.name)) continue;
      let size = 0;
      try {
        size = fs.statSync(full).size;
      } catch {
        continue;
      }
      const isDoc = entry.name.toLowerCase().endsWith('.md');
      sources.push({ rel: entry.name, from: full, size, kind: isDoc ? 'doc' : 'tree' });
      continue;
    }

    if (!entry.isDirectory()) continue;
    for (const item of walk(full)) {
      sources.push({ rel: `${entry.name}/${item.rel}`, from: item.abs, size: item.size, kind: 'tree' });
    }
  }

  return { sources, excludedDirs };
}

/** Every snapshot on disk, newest first. A directory without a manifest is still listed - it is a fact about disk. */
export function listSnapshots(dir = snapshotsDir()) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const found = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (!/^\d{4}-\d{2}-\d{2}$/.test(entry.name)) continue;
    const full = path.join(dir, entry.name);
    let manifest = null;
    try {
      manifest = JSON.parse(fs.readFileSync(path.join(full, MANIFEST), 'utf8'));
    } catch {
      manifest = null;
    }
    let files = 0;
    let bytes = 0;
    for (const entry of walk(full)) {
      if (entry.rel === MANIFEST) continue;
      files++;
      try {
        bytes += fs.statSync(entry.abs).size;
      } catch {
        /* a file that vanished between listing and stat is not worth an error */
      }
    }
    found.push({
      date: entry.name,
      path: full,
      files,
      bytes,
      createdAt: manifest?.createdAt ?? null,
      complete: manifest !== null,
    });
  }
  return found.sort((a, b) => b.date.localeCompare(a.date));
}

/**
 * Delete all but the newest `keep` snapshots.
 *
 * Returns what was removed, so a caller can report it instead of it happening silently. Never removes
 * anything outside the snapshots directory - see `isInside`.
 */
export function pruneSnapshots({ dir = snapshotsDir(), keep = DEFAULT_KEEP_DAYS, now = new Date() } = {}) {
  const removed = [];
  const kept = [];
  const all = listSnapshots(dir);

  // Protected regardless of age: today's snapshot, and anything newer than today (a machine whose clock
  // moved backwards must not lose data to the clock).
  const protective = new Set([today(now)]);
  for (const snap of all) if (snap.date > today(now)) protective.add(snap.date);

  for (let i = 0; i < all.length; i++) {
    const snap = all[i];
    if (i < keep || protective.has(snap.date)) {
      kept.push(snap.date);
      continue;
    }
    const target = path.resolve(snap.path);
    if (!isInside(dir, target)) {
      kept.push(snap.date);
      removed.push({ date: snap.date, path: target, skipped: 'outside snapshots dir' });
      continue;
    }
    try {
      fs.rmSync(target, { recursive: true, force: true });
      removed.push({ date: snap.date, path: target });
    } catch (error) {
      removed.push({ date: snap.date, path: target, error: error?.message ?? String(error) });
    }
  }

  return { removed, kept, keep, dir: path.resolve(dir) };
}

/**
 * Take today's snapshot, replacing today's if it already exists, then prune.
 *
 * Replacing rather than accumulating is the whole point of a daily snapshot: within one day the newest
 * content is the same day's content, and keeping every run would push the interesting older days out
 * of the retention window within a single afternoon.
 */
export function takeSnapshot({ root = workspaceRoot(), dir = snapshotsDir(), keep = DEFAULT_KEEP_DAYS, now = new Date() } = {}) {
  const date = today(now);
  const dest = path.join(dir, date);
  const { sources, excludedDirs } = snapshotSources(root);

  const existedBefore = fs.existsSync(dest);
  if (existedBefore) {
    // Rebuild in place: remove only the snapshot's own directory, verified to be inside `dir`.
    if (!isInside(dir, dest)) {
      return { ok: false, error: `拒绝覆盖 ${dest}：不在快照目录内。` };
    }
    fs.rmSync(dest, { recursive: true, force: true });
  }  fs.mkdirSync(dest, { recursive: true });

  const entries = [];
  let bytes = 0;
  const missing = [];
  for (const source of sources) {
    if (!fs.existsSync(source.from)) {
      missing.push(source.rel);
      continue;
    }
    try {
      const size = copyInto(source.from, path.join(dest, source.rel.split('/').join(path.sep)));
      bytes += size;
      entries.push({ path: source.rel, bytes: size, kind: source.kind });
    } catch (error) {
      missing.push(`${source.rel}（复制失败：${error?.message ?? error}）`);
    }
  }

  const manifest = {
    schema: MANIFEST_SCHEMA,
    schemaVersion: MANIFEST_SCHEMA_VERSION,
    createdAt: now.toISOString(),
    date,
    workspaceRoot: path.resolve(root),
    replaced: existedBefore,
    fileCount: entries.length,
    bytes,
    files: entries,
    ...(missing.length ? { missing } : {}),
    // Which directories were left out. A partial snapshot must never be indistinguishable from a
    // complete one - the failure mode that once let 33 project directories go missing unnoticed.
    excludedDirs,
  };
  fs.writeFileSync(path.join(dest, MANIFEST), JSON.stringify(manifest, null, 2) + '\n', 'utf8');

  // `now` must be handed on. A prune that consults the wall clock instead of the caller's date decides
  // "which day is protected" from a different day than the snapshot it just wrote, which is how a
  // retention window silently keeps the wrong three.
  const pruned = pruneSnapshots({ dir, keep, now });

  return {
    ok: true,
    date,
    path: dest,
    replaced: existedBefore,
    fileCount: entries.length,
    bytes,
    missing,
    excludedDirs,
    pruned,
    kept: pruned.kept,
    snapshots: listSnapshots(dir),
  };
}

/**
 * Build a migration pack: everything needed to continue this work on another machine.
 *
 * Carries the newest snapshot only, plus this plugin's own source. Older snapshots are deliberately left
 * behind - see the module comment.
 */
export function exportMigrationPack({
  root = workspaceRoot(),
  dir = snapshotsDir(),
  outDir = null,
  pluginRoot = null,
  now = new Date(),
  includeState = true,
  stateDir = null,
} = {}) {
  const snapshots = listSnapshots(dir);
  if (!snapshots.length) {
    return {
      ok: false,
      error: `没有找到任何快照（${dir}）。先执行 action=snapshot 生成当天快照，再导出迁移包。`,
      dir: path.resolve(dir),
    };
  }
  const newest = snapshots[0];
  const out = outDir ?? path.join(dir, `migration-pack-${stamp(now)}`);
  const resolvedOut = path.resolve(out);

  // Refuse to write the pack inside a snapshot: it would be swept away by the next rebuild of that day.
  if (isInside(dir, resolvedOut)) {
    const snap = snapshots.find((s) => isInside(s.path, resolvedOut));
    if (snap) return { ok: false, error: `输出目录不能位于快照 ${snap.date} 内：${resolvedOut}` };
  }
  if (fs.existsSync(resolvedOut)) {
    return { ok: false, error: `输出目录已存在，拒绝覆盖：${resolvedOut}` };
  }

  /*
   * 命名提醒：默认名是 migration-pack-YYYYMMDD-HHMMSS，与 snapshots/ 里已有的包保持一致。
   * 自定义 outDir 时很容易写成「项目名-日期」，两个问题：
   *   1) 没有 migration-pack- 前缀，和快照目录里的日期目录混在一起，看不出哪个是包；
   *   2) 只带日期，同一天导出第二次会被「目录已存在」拒掉，或被迫改名。
   * 只提醒、不拒绝——用户可能另有归档体系。
   */
  const outBase = path.basename(resolvedOut);
  const namingHint = /^migration-pack-\d{8}-\d{6}$/.test(outBase)
    ? null
    : `输出目录名不符合约定（期望 migration-pack-YYYYMMDD-HHMMSS，例如 migration-pack-${stamp(now)}），当前是「${outBase}」。包已照常导出。`;

  fs.mkdirSync(resolvedOut, { recursive: true });

  // 1. the newest snapshot, verbatim
  const snapshotDest = path.join(resolvedOut, 'workspace-snapshot');
  fs.cpSync(newest.path, snapshotDest, { recursive: true });

  // 2. the plugin source, so the other machine can run the same tools
  let pluginCopied = null;
  if (pluginRoot && fs.existsSync(pluginRoot)) {
    const dest = path.join(resolvedOut, 'plugin');
    fs.cpSync(pluginRoot, dest, {
      recursive: true,
      filter: (src) => !shouldSkip(path.basename(src)) && path.basename(src) !== '.git',
    });
    pluginCopied = dest;
  }

  // 3. the plugin's own install state (not the path-keyed cursors)
  let stateCopied = null;
  if (includeState) {
    const src = stateDir ?? path.join(os.homedir(), '.dsh', 'rimworld-log');
    const file = path.join(src, 'install-state.json');
    if (fs.existsSync(file)) {
      const dest = path.join(resolvedOut, 'plugin-state');
      fs.mkdirSync(dest, { recursive: true });
      fs.copyFileSync(file, path.join(dest, 'install-state.json'));
      stateCopied = path.join(dest, 'install-state.json');
    }
  }

  const carried = walk(resolvedOut).map((entry) => entry.rel);
  const pack = {
    schema: PACK_SCHEMA,
    schemaVersion: 1,
    createdAt: now.toISOString(),
    workspaceRoot: path.resolve(root),
    snapshotsAvailable: snapshots.map((s) => s.date),
    snapshotIncluded: newest.date,
    snapshotCreatedAt: newest.createdAt,
    snapshotFiles: newest.files,
    olderSnapshotsOmitted: snapshots.slice(1).map((s) => s.date),
    pluginRoot: pluginCopied ? path.resolve(pluginRoot) : null,
    pluginStateIncluded: stateCopied !== null,
    fileCount: carried.length,
    files: carried,
    note: '迁移包只携带最新一份快照。更早的快照仍留在快照目录中，未随包导出。',
  };
  fs.writeFileSync(path.join(resolvedOut, 'manifest.json'), JSON.stringify(pack, null, 2) + '\n', 'utf8');

  return {
    ok: true,
    path: resolvedOut,
    snapshotIncluded: newest.date,
    omitted: pack.olderSnapshotsOmitted,
    fileCount: carried.length + 1,
    pluginIncluded: pluginCopied !== null,
    stateIncluded: stateCopied !== null,
    snapshotsAvailable: pack.snapshotsAvailable,
    namingHint,
  };
}

/**
 * Directory holding hand-written archive notes.
 *
 * Why a separate directory from snapshots: a snapshot is a byte-for-byte copy of the work area, so
 * anything written into the work area automatically lands in the next snapshot. Notes are the part a
 * snapshot cannot provide - the reason something was done, what was ruled out, what is still open.
 * Keeping them at `<workspace>/归档/` means they are ordinary readable files the user can open
 * without unpacking anything, and they are still carried by every snapshot.
 *
 * Overridable with `RIMLOG_ARCHIVE_NOTE_DIR` for a work area that already has its own filing system.
 */
export function archiveNoteDir(root = workspaceRoot()) {
  return process.env.RIMLOG_ARCHIVE_NOTE_DIR ?? path.join(root, '归档');
}

/** Turn a title into something that is safe as a Windows filename and still readable. */
function slugForFileName(title) {
  const cleaned = String(title ?? '')
    .replace(/[\\/:*?"<>|]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const trimmed = cleaned.length > 60 ? cleaned.slice(0, 60).trim() : cleaned;
  return trimmed || '未命名';
}

/**
 * Write one archive note and register it in `INDEX.md`.
 *
 * The index is the part that makes notes usable months later: without it, finding "when did we fix
 * the CE melee penetration" means opening every file. The index is regenerated from disk on every
 * write rather than appended to, so a hand-deleted note disappears from it instead of leaving a
 * dangling row.
 *
 * Never throws for the normal failure modes; returns `{ ok: false, error }` so a caller that is
 * archiving as a side effect (log scan) can decide to ignore it.
 */
export function writeArchiveNote({
  title,
  body,
  tags = [],
  root = workspaceRoot(),
  now = new Date(),
} = {}) {
  try {
    if (!title || !String(title).trim()) return { ok: false, error: 'title 不能为空' };
    if (!workspaceExists(root)) return { ok: false, error: `工作区不存在：${root}` };

    const dir = archiveNoteDir(root);
    fs.mkdirSync(dir, { recursive: true });

    const stamp = `${today(now)} ${String(now.getHours()).padStart(2, '0')}${String(now.getMinutes()).padStart(2, '0')}`;
    const slug = slugForFileName(title);
    const file = path.join(dir, `${stamp} - ${slug}.md`);

    const tagLine = tags.length ? `tags: ${tags.join(', ')}` : 'tags:';
    const content = [
      `# ${String(title).trim()}`,
      '',
      `- 时间：${stamp.replace(' ', ' ')}`,
      `- ${tagLine}`,
      '',
      String(body ?? '').trim(),
      '',
    ].join('\n');
    fs.writeFileSync(file, content, 'utf8');

    // Rebuild the index from what is actually on disk.
    const notes = fs.readdirSync(dir)
      .filter((name) => name.toLowerCase().endsWith('.md') && name !== 'INDEX.md')
      .sort();
    const rows = notes.map((name) => {
      const text = fs.readFileSync(path.join(dir, name), 'utf8');
      const firstTagLine = (text.match(/^- tags:(.*)$/m)?.[1] ?? '').trim();
      const label = name.replace(/\.md$/i, '');
      return `| ${label} | ${firstTagLine || '-'} |`;
    });
    const index = [
      '# 归档索引',
      '',
      '> 由插件自动维护。每次写入归档都会按磁盘实际内容重建，因此手工删除的条目也会消失。',
      '',
      '| 条目 | 标签 |',
      '|---|---|',
      ...rows,
      '',
    ].join('\n');
    fs.writeFileSync(path.join(dir, 'INDEX.md'), index, 'utf8');

    return { ok: true, path: file, dir, index: path.join(dir, 'INDEX.md'), count: notes.length };
  } catch (error) {
    return { ok: false, error: error instanceof Error ? error.message : String(error) };
  }
}

/** One-line summary used by the tool's text output and by the feature report. */
export function archiveSummary({ dir = snapshotsDir(), keep = DEFAULT_KEEP_DAYS } = {}) {
  const snapshots = listSnapshots(dir);
  return {
    dir: path.resolve(dir),
    keep,
    count: snapshots.length,
    newest: snapshots[0]?.date ?? null,
    oldest: snapshots.at(-1)?.date ?? null,
    snapshots,
  };
}

/**
 * Verify a snapshot against the live workspace: file list + hash comparison.
 *
 * Answers the question the manual check kept answering by hand: "did the backup actually capture
 * everything, and is any of it stale?" Three checks, in order of severity:
 *  - files present in one but not the other (the snapshot missed something, or the workspace
 *    grew after the snapshot was taken);
 *  - common files whose hash differs (the file changed since the snapshot);
 *  - accounting for the deliberately skipped directories, so the "missing" count is explained
 *    rather than mysterious.
 *
 * Full hash on every common file: ~1375 files read once, roughly 1–2 seconds. A sampled check was
 * considered and rejected — the point of `verify` is to certify, and a sample can only raise doubt.
 *
 * @param {object} [options]
 * @param {string} [options.date] - which snapshot to verify; defaults to the newest.
 * @param {string} [options.root] - workspace root; defaults to `workspaceRoot()`.
 * @param {string} [options.dir] - snapshots dir; defaults to `snapshotsDir()`.
 * @param {number} [options.listLimit] - max entries per diff section, default 30.
 */
export function verifySnapshot({ date, root = workspaceRoot(), dir = snapshotsDir(), listLimit = 30 } = {}) {
  const snapshots = listSnapshots(dir);
  if (snapshots.length === 0) {
    return { ok: false, error: `快照目录里没有任何快照: ${path.resolve(dir)}` };
  }
  const target = date
    ? snapshots.find((s) => s.date === date)
    : snapshots[0];
  if (!target) {
    return { ok: false, error: `没有日期为 ${date} 的快照。可用的: ${snapshots.map((s) => s.date).join(', ')}` };
  }

  // Workspace side: exactly what snapshotSources would take (same filter, same skip rules).
  const { sources, excludedDirs } = snapshotSources(root);
  const workspaceByRel = new Map(sources.map((s) => [s.rel, s]));

  // Snapshot side: what actually landed on disk (walk applies the same DEFAULT_EXCLUDE).
  const snapshotFiles = walk(target.path).filter((f) => f.rel !== MANIFEST);
  const snapshotByRel = new Map(snapshotFiles.map((f) => [f.rel, f]));

  // ---- File list diff ----
  const onlyInWorkspace = [];
  const onlyInSnapshot = [];
  for (const rel of workspaceByRel.keys()) {
    if (!snapshotByRel.has(rel)) onlyInWorkspace.push(rel);
  }
  for (const rel of snapshotByRel.keys()) {
    if (!workspaceByRel.has(rel)) onlyInSnapshot.push(rel);
  }

  // ---- Hash comparison on common files ----
  const hashOf = (file) => {
    try {
      return createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 16);
    } catch {
      return null;
    }
  };
  let compared = 0;
  let hashMismatches = 0;
  const mismatchedFiles = [];
  for (const [rel, wsFile] of workspaceByRel) {
    const snapFile = snapshotByRel.get(rel);
    if (!snapFile) continue;
    const a = hashOf(wsFile.from);
    const b = hashOf(snapFile.abs);
    compared += 1;
    if (a === null || b === null || a !== b) {
      hashMismatches += 1;
      if (mismatchedFiles.length < listLimit) mismatchedFiles.push(rel);
    }
  }

  // ---- Accounting for the deliberately skipped directories ----
  const skippedAccounting = excludedDirs.map((name) => {
    const full = path.join(root, name);
    // Walk WITHOUT the exclude filter so the count reflects what was actually left out.
    const raw = (() => {
      const out = [];
      const rawWalk = (d) => {
        let entries;
        try {
          entries = fs.readdirSync(d, { withFileTypes: true });
        } catch {
          return;
        }
        for (const entry of entries) {
          const f = path.join(d, entry.name);
          if (entry.isDirectory()) rawWalk(f);
          else if (entry.isFile()) {
            try {
              out.push(fs.statSync(f).size);
            } catch {
              /* skip */
            }
          }
        }
      };
      rawWalk(full);
      return out;
    })();
    return {
      name,
      files: raw.length,
      bytes: raw.reduce((s, n) => s + n, 0),
    };
  });

  const totalSkippedBytes = skippedAccounting.reduce((s, a) => s + a.bytes, 0);

  return {
    ok: true,
    date: target.date,
    snapshotPath: path.resolve(target.path),
    workspace: {
      root: path.resolve(root),
      files: workspaceByRel.size,
      bytes: sources.reduce((s, f) => s + f.size, 0),
    },
    snapshot: {
      files: snapshotByRel.size,
      bytes: snapshotFiles.reduce((s, f) => s + f.size, 0),
    },
    onlyInWorkspace: {
      count: onlyInWorkspace.length,
      files: onlyInWorkspace.slice(0, listLimit),
    },
    onlyInSnapshot: {
      count: onlyInSnapshot.length,
      files: onlyInSnapshot.slice(0, listLimit),
    },
    hashCheck: {
      compared,
      mismatches: hashMismatches,
      files: mismatchedFiles,
    },
    skipped: {
      dirs: skippedAccounting,
      files: skippedAccounting.reduce((s, a) => s + a.files, 0),
      bytes: totalSkippedBytes,
    },
    verdict: onlyInWorkspace.length === 0 && onlyInSnapshot.length === 0 && hashMismatches === 0
      ? `快照 ${target.date} 与工作区完全一致（${compared} 个文件逐一哈希核对）`
      : `快照 ${target.date} 与工作区有差异：${onlyInWorkspace.length} 个仅工作区有、${onlyInSnapshot.length} 个仅快照有、${hashMismatches} 个哈希不同`,
  };
}

